'use strict';
// node tests/semesta-daynight.test.cjs
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..','world-builder');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const window={};vm.runInNewContext(read('semesta-daynight.js'),{window});
const e=window.VLSemestaDayNight;
const c=e.makeClock({day:1,minute:420,speed:1});
assert.equal(c.label(),'07:00');
c.tick(60);assert.equal(c.label(),'08:00','one real minute = one virtual hour');
c.setSpeed(4);c.tick(60);assert.equal(c.label(),'12:00','4× clock speed');
c.setPaused(true);c.tick(60);assert.equal(c.label(),'12:00','paused clock does not advance');
c.setPaused(false);
c.setMinute(1439);c.tick(2);
assert.equal(c.label(),'00:07','midnight rollover preserves 24h format');
assert.equal(c.get().day,2);
assert.equal(c.weekday(),'SEL');
assert.equal(e.DAY_REAL_SECONDS,1440,'one full day lasts 24 real minutes at 1×');
const sunrise=e.model(420),noon=e.model(720),sunset=e.model(1035),midnight=e.model(0);
assert.equal(sunrise.phase,'PAGI');
assert.equal(noon.phase,'SIANG');
assert.equal(midnight.phase,'MALAM');
assert.ok(noon.sun.height>sunrise.sun.height&&noon.sun.height>sunset.sun.height);
assert.ok(midnight.glow>noon.glow,'streetlights on at night');
assert.ok(midnight.night>noon.night,'night color grade');
assert.ok(sunrise.sun.z*sunset.sun.z<0,'morning and evening cast directions differ');
assert.ok(sunrise.cast>midnight.cast);
assert.equal(e.format(1440),'00:00');
const clock=e.makeClock({day:7,minute:1430,speed:2});
clock.tick(10);assert.equal(clock.get().day,8);assert.equal(clock.label(),'00:10');
assert.equal(clock.weekday(),'SEN');
const schema=read('map-schema.js'),builder=read('builder.js'),html=read('index.html');
assert.match(builder,/const dayClock=window\.VLSemestaDayNight\.makeClock/);
assert.match(builder,/function restoreCityClock/);
assert.match(builder,/function syncClockToMap/);
assert.match(builder,/worldEffects\.update\(elapsedReal,dayClock\.solar\(\)\)/);
assert.match(builder,/dayClock\.tick\(elapsedReal\)/);
assert.match(builder,/getAgent:id=>automatedAgents\.get\(id\)/);
assert.match(builder,/getRoot:id=>owners\.get\(id\)/);
assert.match(builder,/documentMap\.map\.environmentClock=dayClock\.snapshot\(\)/);
for(const id of ['timeToggle','timeDisplay','timeDay','timePhase','timePanel',
 'timeScrub','timeSpeed','timePause','timeMorning','dayNightTint','nightGlow'])
 assert.match(html,new RegExp('id="'+id+'"'));
const src=html.match(/<script[^>]+src="([^"]+)"/g).join('\n');
assert.ok(src.indexOf('semesta-daynight.js')<src.indexOf('builder.js'));
assert.ok(src.indexOf('semesta-world-effects.js')<src.indexOf('builder.js'));
assert.match(read('semesta-world-effects.js'),/new THREE\.InstancedMesh/);
assert.match(read('semesta-world-effects.js'),/o\.type==='crowd'/);
assert.match(read('semesta-world-effects.js'),/p\.kind==='building'&&isOutline\(\)/);
assert.match(read('semesta-world-effects.js'),/model\.glow/);
assert.match(schema,/doc\.map=\{\.\.\.doc\.map/);
assert.match(read('xp.css'),/#dayNightTint,#nightGlow\{[^}]*pointer-events:none/);
console.log('Semesta 24-hour clock / sun position / dynamic shadows / night lamps PASS');
