'use strict';
// Run: node tests/world-physics.test.cjs
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..','world-builder');
const window={};
const context=vm.createContext({window});
for(const name of ['style-rules.js','map-terrain.js','world-physics.js']){
 vm.runInContext(fs.readFileSync(path.join(root,name),'utf8'),context,{filename:name});
}
const style=window.VLWorldStyle,physics=window.VLWorldPhysics;
const catalog=new Map();
const player={id:'player',type:'avatar',x:0,z:0,rotation:0,scale:1,collision:true};
const building={id:'office',type:'building',x:2,z:0,w:2,d:2,h:6,scale:1,rotation:0,collision:true};
const bench={id:'bench',type:'bench',x:-2,z:0,scale:1,collision:true};
const tree={id:'tree',type:'tree',x:0,z:-2,scale:1,collision:true};
const solidNPC={id:'npc',type:'npc',x:0,z:2,scale:1,collision:true};
const items=[player,building,bench,tree,solidNPC];
const map={unbounded:true,terrain:{default:'grass',cells:[]}};
const walk=(dx,dz)=>physics.move(player,{x:0,z:0},dx,dz,items,map,catalog,style,new Map());
assert.ok(walk(4,0).x<.75,'actor must stop at office wall');
assert.ok(walk(-4,0).x>-.8,'actor must stop at bench');
assert.ok(walk(0,-4).z>-.85,'actor must stop at tree');
assert.ok(walk(0,4).z<1.4,'actor must stop at another actor');
const diagonal=walk(1,1);
assert.ok(diagonal.z>.5,'diagonal movement should slide along blocking object');
const water={unbounded:true,terrain:{default:'grass',cells:[{c:5,r:0,type:'water'}]}};
assert.equal(physics.check(player,{x:5.3,z:.5},items,water,catalog,style).reason,'water');
const passable={id:'ghost',type:'building',x:1,z:0,w:4,d:4,collision:false,scale:1,rotation:0};
assert.equal(physics.check(player,{x:1,z:0},[player,passable],map,catalog,style).ok,true);
assert.ok(style.reason({...player,x:2,z:0},items,map,catalog),'placed actor cannot overlap solids');
assert.equal(physics.bigStructure(building,catalog,style),false,'small object does not auto-fade');
assert.equal(physics.bigStructure({...building,w:8,d:6},catalog,style),true,'large building may fade');
assert.equal(physics.bigStructure({...building,w:8,d:6,blocking:'no'},catalog,style),false);
assert.equal(physics.bigStructure(tree,catalog,style),false,'trees do not fade');
const rotated={...building,w:10,d:4,rotation:90};
const box=physics.bigBox(rotated,catalog,style);
assert.equal(Math.round(box.max.x-box.min.x),4,'rotated world box swaps width/depth');
const engine=fs.readFileSync(path.join(root,'builder.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const tutorial=fs.readFileSync(path.join(root,'quick-tutorial.js'),'utf8');
assert.match(engine,/physics\.move\(actor,start/);
assert.match(engine,/updateLargeOcclusion\(dt\)/);
assert.match(html,/id="tutorialOverlay"/);
assert.match(html,/id="openTutorial"/);
assert.match(html,/world-physics\.js/);
assert.equal((tutorial.match(/icon:'/g)||[]).length,5);
console.log('Virtual Life solid-world / occlusion / quick tutorial: PASS');
